"""
agent_loop.py — Agent Smith's orchestrator (Section 4.1).

This is the piece that ties everything else together:

    LLM provider  -->  code extraction  -->  sandbox execution
         ^                                          |
         |                Observation               |
         +------------------------------------------+

One AgentLoop instance runs ONE task (MBPP or SWE-bench -- it doesn't care
which; the difference lives entirely in the task prompt text and in which
MCP server the sandbox is connected to). It produces a SolutionOutput,
ready to be written to solution.json.

Benchmark-specific CLIs (agent_mbpp, agent_swebench) are a thin layer on
top of this: load a task, build a task prompt, construct an AgentLoop with
the right sandbox/MCP connection and limits, call .run(), serialize the
result.
"""

from __future__ import annotations

import time
from datetime import datetime
from typing import List, Optional

from pydantic import BaseModel, Field

from code_extraction import extract_code, feedback_text
from llm_provider import AllProvidersExhaustedError, LLMProviderError
from sandbox import Sandbox


# ---------------------------------------------------------------------------
# Required output models (Section 4.1.1, verbatim shape)
# ---------------------------------------------------------------------------


class StepMetrics(BaseModel):
    """Metrics for a single agent step.

    Each step corresponds to one LLM generate -> sandbox execute cycle.
    All fields are required for evaluation, empty strings are acceptable
    for steps where a field doesn't apply (e.g., no sandbox execution).
    """

    step: int = Field(..., description="1-indexed iteration number")
    input_tokens: int = Field(..., description="Tokens sent to the LLM for this step")
    output_tokens: int = Field(..., description="Tokens generated by the LLM for this step")
    request_time_ms: float = Field(..., description="Wall-clock time for the LLM API call in milliseconds")
    timestamp: str = Field(default_factory=lambda: datetime.now().isoformat(),
                            description="ISO 8601 timestamp of when this step was recorded")
    api_url: str = Field(default="", description="Base URL of the LLM API endpoint")
    model_name: str = Field(default="", description="Model identifier used for this step")
    llm_output: str = Field(default="", description="Raw text generated by the LLM before code extraction")
    sandbox_input: str = Field(default="", description="Python code sent to the sandbox for execution")
    sandbox_output: str = Field(default="", description="Sandbox execution result (stdout/stderr/error message)")
    retries: int = Field(default=0, description="Number of LLM API retries before getting a successful response")


class SolutionOutput(BaseModel):
    """Output from student solution, required format for evaluation.

    This is the JSON structure your agent must produce and write to solution.json.
    The moulinette validates this against task correctness and metrics limits.
    """

    task_id: str = Field(..., description="Task identifier (MBPP task_id as string, or SWE-bench instance_id)")
    benchmark: str = Field(..., description="Benchmark type: 'mbpp' or 'swebench'")
    success: bool = Field(..., description="Whether the agent believes it solved the task")
    solution: str = Field(..., description="For MBPP: the Python function code. For SWE-bench: the git patch (diff)")
    iterations: int = Field(..., description="Number of agent loop iterations used")
    total_requests: int = Field(..., description="Total number of LLM API requests made (including retries)")
    total_input_tokens: int = Field(..., description="Sum of input_tokens across all steps")
    total_output_tokens: int = Field(..., description="Sum of output_tokens across all steps")
    total_time_seconds: float = Field(..., description="Wall-clock time from agent start to finish")
    steps: List[StepMetrics] = Field(default_factory=list, description="Per-step metrics, one entry per agent iteration")
    system_prompt: str = Field(default="", description="Full system prompt sent to the LLM (for provenance checking)")
    error: Optional[str] = Field(default=None, description="Error message if the agent failed (None if successful)")
    timestamp: str = Field(default_factory=lambda: datetime.now().isoformat(),
                            description="ISO 8601 timestamp of when the solution was produced")


# ---------------------------------------------------------------------------
# System prompt (Section 4.1, point 6)
# ---------------------------------------------------------------------------


DEFAULT_EXAMPLE = """--- Example of an effective reasoning loop ---

Thought: I need to find where the bug is before I can fix it.
Code:
```python
result = search_code("def is_valid_email")
print(result)
```
<end_code>

(Observation: /testbed/src/mail.py:65 def is_valid_email(email: str) -> bool:)

Thought: Found it. Let me read the surrounding code to understand the current logic.
Code:
```python
result = read_file("/testbed/src/mail.py", 60, 75)
print(result)
```
<end_code>

(Observation: shows a regex pattern missing the '+' character class)

Thought: The regex is missing a character. I'll fix it directly.
Code:
```python
edit_file("/testbed/src/mail.py", "[a-zA-Z0-9_.-]+@", "[a-zA-Z0-9_.+-]+@")
result = run_tests()
print(result)
```
<end_code>

(Observation: {"exit_code": 0, "stdout": "All tests passed", "stderr": ""})

Thought: Tests pass. I'll submit the patch.
Code:
```python
final_answer(get_patch())
```
<end_code>

"""


def build_system_prompt(sandbox_manual: str, task_hint: str = "", example: str = DEFAULT_EXAMPLE) -> str:
    """Dynamically assembled from the connected sandbox's manual, so it
    always reflects whichever MCP server (MBPP or SWE-bench, or an unknown
    one) is actually wired up -- per Section 4.2 point 5."""

    return f"""You are an autonomous coding agent. You solve tasks by writing and \
executing Python code inside a sandbox, one step at a time, observing the \
result of each step before deciding what to do next.

Follow this exact loop for every step:

  Thought: <your reasoning about what to try next, in one or two sentences>
  Code:
  ```python
  <the Python code to run this step>
  ```

After you submit a Code block, it is executed in the sandbox and you will
be given an Observation showing what happened. You then continue with a
new Thought/Code pair based on that Observation. Do not write an
Observation yourself -- it will be provided to you.

When you are confident you have solved the task, call `final_answer(...)`
with your solution as the final statement of a Code block. This ends the
task immediately.

{sandbox_manual}

{task_hint}

{example}--- Rules ---

- Always put your code inside a single ```python ... ``` block.
- End every Code block with the literal marker <end_code> so execution can begin --
  do not keep writing after it, and never fabricate what the Observation will say.
- Only call tools that were listed above. Do not assume other tools exist.
- If a step's Observation shows an error, read it carefully before trying again --
  do not repeat the same failing code unchanged.
- Call final_answer(...) exactly once, only when you are done.
"""


# ---------------------------------------------------------------------------
# Context trimming
# ---------------------------------------------------------------------------
#
# Every request resends the whole history and input tokens are counted
# cumulatively, so an untrimmed history costs O(steps^2). The full
# transcript is kept in `messages` (and in StepMetrics); only the copy sent
# to the LLM is compacted: the last few steps stay verbatim, older ones
# are clipped to what the model needs to remember what it already did.

KEEP_RECENT_STEPS = 3          # assistant/observation pairs sent verbatim
MAX_OBSERVATION_CHARS = 4000   # cap on a fresh observation (sandbox caps at 8000)
OLD_OBSERVATION_CHARS = 300    # older observations: just enough to recall the outcome
OLD_ASSISTANT_CHARS = 800      # older replies: the Thought and the start of the code
MAX_OLD_STEPS = 8             # clipped pairs kept before them; anything older is dropped
REPEAT_WINDOW = 4              # how far back identical code counts as a repeat


def clip_middle(text: str, limit: int, label: str) -> str:
    """Keeps the head and the tail of `text` -- tracebacks and test
    summaries end at the tail -- and marks what was cut."""
    if len(text) <= limit:
        return text
    head = limit * 2 // 3
    tail = limit - head
    return f"{text[:head]}\n[... {len(text) - limit} chars {label} ...]\n{text[-tail:]}"


def compact_history(messages: List[dict], keep_recent: int = KEEP_RECENT_STEPS) -> List[dict]:
    """messages = [system, kickoff, (assistant, observation)*]. Returns the
    prompt to send: the preamble and the last `keep_recent` pairs as-is, the
    MAX_OLD_STEPS pairs before them clipped, and anything older dropped
    (whole pairs, so user/assistant turns still alternate)."""
    system, kickoff = messages[0], messages[1]
    turns = messages[2:]
    dropped = max(0, len(turns) // 2 - keep_recent - MAX_OLD_STEPS)
    if dropped:
        kickoff = {**kickoff, "content": f"{kickoff['content']}\n[Steps 1-{dropped} omitted to save context.]"}
        turns = turns[2 * dropped:]
    cutoff = len(turns) - 2 * keep_recent
    compacted = [system, kickoff]
    for i, message in enumerate(turns):
        if i < cutoff:
            limit = OLD_ASSISTANT_CHARS if message["role"] == "assistant" else OLD_OBSERVATION_CHARS
            message = {**message, "content": clip_middle(message["content"], limit, "elided from an earlier step")}
        compacted.append(message)
    return compacted


# ---------------------------------------------------------------------------
# The loop itself
# ---------------------------------------------------------------------------


class AgentLoop:
    def __init__(
        self,
        provider,                      # anything with .generate(messages, stop, max_tokens, temperature) -> LLMResponse
        sandbox: Sandbox,
        max_iterations: int = 10,
        max_input_tokens: int = 6000,
        max_output_tokens: int = 1500,
        max_output_tokens_per_step: int = 512,
        timeout_seconds: int = 120,
        stop_sequences: Optional[List[str]] = None,
        example: str = DEFAULT_EXAMPLE,
    ):
        self.provider = provider
        self.sandbox = sandbox
        self.max_iterations = max_iterations
        self.max_input_tokens = max_input_tokens
        self.max_output_tokens = max_output_tokens
        self.max_output_tokens_per_step = max_output_tokens_per_step
        self.timeout_seconds = timeout_seconds
        self.stop_sequences = stop_sequences or ["<end_code>"]
        self.example = example

    @staticmethod
    def _estimate_next_input(prompt: List[dict], chars_per_token: float) -> int:
        """Token count of the next (compacted) request. chars_per_token is
        calibrated on the provider's own count for the previous request;
        the 0.9 margin and +32 (chat-template overhead) keep it on the high side."""
        chars = sum(len(m["content"]) for m in prompt)
        return int(chars / (chars_per_token * 0.9)) + 32

    def run(self, task_prompt: str, task_id: str, benchmark: str) -> SolutionOutput:
        system_prompt = build_system_prompt(self.sandbox.manual_text(), task_hint=task_prompt, example=self.example)
        messages: List[dict] = [
            {"role": "system", "content": system_prompt},
            {"role": "user", "content": "Begin. Provide your first Thought/Code pair."},
        ]

        steps: List[StepMetrics] = []
        total_input_tokens = 0
        total_output_tokens = 0
        total_requests = 0
        success = False
        solution = ""
        error: Optional[str] = None

        start = time.monotonic()
        chars_per_token = 3.0  # recalibrated after every request

        for step_num in range(1, self.max_iterations + 1):
            elapsed = time.monotonic() - start
            if elapsed >= self.timeout_seconds:
                error = f"Stopped after {elapsed:.1f}s: internal timeout of {self.timeout_seconds}s reached."
                break
            # Input tokens are cumulative and every request resends the
            # (compacted) history, so check that the NEXT request fits -- not
            # just that we're under the limit now -- or the last step overshoots it.
            prompt = compact_history(messages)
            if total_input_tokens + self._estimate_next_input(prompt, chars_per_token) > self.max_input_tokens:
                error = f"Stopped: next request would exceed the cumulative input token limit ({self.max_input_tokens})."
                break
            if total_output_tokens >= self.max_output_tokens:
                error = f"Stopped: cumulative output token limit ({self.max_output_tokens}) reached."
                break

            # -- 1. Ask the LLM for the next Thought/Code pair --------------
            try:
                response = self.provider.generate(
                    messages=prompt,
                    stop=self.stop_sequences,
                    max_tokens=min(
                        self.max_output_tokens_per_step,
                        self.max_output_tokens - total_output_tokens,
                    ),
                    temperature=0.0,
                )
            except (AllProvidersExhaustedError, LLMProviderError) as e:
                error = f"LLM request failed at step {step_num}: {e}"
                break

            total_requests += 1 + response.retries
            total_input_tokens += response.input_tokens
            total_output_tokens += response.output_tokens
            if response.input_tokens > 0:
                chars_per_token = sum(len(m["content"]) for m in prompt) / response.input_tokens
            messages.append({"role": "assistant", "content": response.text})

            # -- 2. Extract executable code from the raw response -----------
            extraction = extract_code(response.text)
            note = feedback_text(extraction)

            if not extraction.found:
                # Section 4.1: "No valid code block was found" -- explicit
                # feedback, no sandbox call, no silent failure.
                observation = note
                steps.append(StepMetrics(
                    step=step_num,
                    input_tokens=response.input_tokens,
                    output_tokens=response.output_tokens,
                    request_time_ms=response.request_time_ms,
                    api_url=response.api_url,
                    model_name=response.model_name,
                    llm_output=response.text,
                    sandbox_input="",
                    sandbox_output=observation,
                    retries=response.retries,
                ))
                messages.append({"role": "user", "content": f"Observation:\n{observation}"})
                continue

            # -- 3. Run it in the sandbox ------------------------------------
            result = self.sandbox.execute(extraction.code)  # KeyboardInterrupt/SystemExit propagate through here
            observation = (f"{note}\n{result.output}" if note else result.output)
            # At temperature 0 a model that repeats itself gets the same
            # prompt back and loops until the budget runs out; say so
            # explicitly, which also changes the prompt.
            repeat_of = next(
                (s.step for s in reversed(steps[-REPEAT_WINDOW:]) if s.sandbox_input == extraction.code),
                None,
            )
            if repeat_of is not None:
                observation = (
                    f"WARNING: this is exactly the code you ran at step {repeat_of}. Repeating it "
                    f"will not make progress -- try a different approach, or call final_answer(...) "
                    f"if the task is already solved.\n{observation}"
                )

            steps.append(StepMetrics(
                step=step_num,
                input_tokens=response.input_tokens,
                output_tokens=response.output_tokens,
                request_time_ms=response.request_time_ms,
                api_url=response.api_url,
                model_name=response.model_name,
                llm_output=response.text,
                sandbox_input=extraction.code,
                sandbox_output=observation,
                retries=response.retries,
            ))

            if result.is_final_answer:
                success = True
                solution = str(result.final_answer_value)
                break

            # StepMetrics keeps the full output; the LLM gets a capped copy.
            observation = clip_middle(observation, MAX_OBSERVATION_CHARS, "truncated, print a narrower slice if you need it")
            messages.append({"role": "user", "content": f"Observation:\n{observation}"})
        else:
            error = f"Stopped: max_iterations ({self.max_iterations}) reached without final_answer."

        if not success and error is None:
            # loop exited via `break` for a token/timeout/provider reason above,
            # `error` is already set in that case; this branch only catches the
            # (rare) case of falling out without one of those being hit.
            error = "Agent loop ended without calling final_answer()."

        return SolutionOutput(
            task_id=task_id,
            benchmark=benchmark,
            success=success,
            solution=solution,
            iterations=len(steps),
            total_requests=total_requests,
            total_input_tokens=total_input_tokens,
            total_output_tokens=total_output_tokens,
            total_time_seconds=time.monotonic() - start,
            steps=steps,
            system_prompt=system_prompt,
            error=None if success else error,
        )